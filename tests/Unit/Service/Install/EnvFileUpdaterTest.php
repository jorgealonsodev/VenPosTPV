<?php

declare(strict_types=1);

namespace VenPosTPV\Tests\Unit\Service\Install;

use PHPUnit\Framework\TestCase;
use Symfony\Component\Dotenv\Dotenv;
use VenPosTPV\Service\Install\EnvFileUpdater;
use VenPosTPV\Service\Install\InstallException;

final class EnvFileUpdaterTest extends TestCase
{
    private string $dir;

    protected function setUp(): void
    {
        $this->dir = sys_get_temp_dir() . '/tpv-envupdate-' . bin2hex(random_bytes(4));
        mkdir($this->dir);
    }

    protected function tearDown(): void
    {
        foreach (glob($this->dir . '/{,.}*', GLOB_BRACE) ?: [] as $f) {
            if (is_file($f)) {
                unlink($f);
            }
        }
        @rmdir($this->dir);
    }

    private function writeEnv(string $content): void
    {
        file_put_contents($this->dir . '/.env', $content);
        chmod($this->dir . '/.env', 0600);
    }

    public function testItReplacesAndAddsOnlyTheGivenKeysAndKeepsABackup(): void
    {
        $before = "# Generated by the VenPosTPV installer\nAPP_ENV='prod'\nAPP_SECRET='keep-me'\nPS_SHOP_URL='https://old.example.com'\nPS_API_KEY='OLDKEY'\n\n# comment stays\nTPV_DB_PASSWORD='p\"w'\"'\"'x'\n";
        $this->writeEnv($before);

        $backup = (new EnvFileUpdater($this->dir))->update(['PS_SHOP_URL' => 'https://new.example.com', 'PS_API_KEY' => 'NEWKEY', 'SSO_SHARED_SECRET' => "s'ecret"], []);

        $after = (new Dotenv())->parse((string) file_get_contents($this->dir . '/.env'));
        self::assertSame('https://new.example.com', $after['PS_SHOP_URL']);
        self::assertSame('NEWKEY', $after['PS_API_KEY']);
        self::assertSame("s'ecret", $after['SSO_SHARED_SECRET']);
        self::assertSame('keep-me', $after['APP_SECRET']);
        self::assertSame("p\"w'x", $after['TPV_DB_PASSWORD']);
        self::assertStringContainsString("# comment stays\n", (string) file_get_contents($this->dir . '/.env'));
        self::assertSame(0600, fileperms($this->dir . '/.env') & 0777);

        self::assertMatchesRegularExpression('/^\.env\.bak-\d{8}-\d{6}(-\d+)?$/', $backup);
        self::assertSame($before, file_get_contents($this->dir . '/' . $backup));
        self::assertSame(0600, fileperms($this->dir . '/' . $backup) & 0777);
        self::assertSame([], glob($this->dir . '/.env.tmp-*'));
    }

    public function testTwoUpdatesInTheSameSecondKeepBothBackups(): void
    {
        $this->writeEnv("PS_API_KEY='A'\n");
        $updater = new EnvFileUpdater($this->dir);

        $first = $updater->update(['PS_API_KEY' => 'B'], []);
        $second = $updater->update(['PS_API_KEY' => 'C'], []);

        self::assertNotSame($first, $second);
        self::assertSame("PS_API_KEY='A'\n", file_get_contents($this->dir . '/' . $first));
        self::assertStringContainsString("PS_API_KEY='B'", (string) file_get_contents($this->dir . '/' . $second));
    }

    public function testWithoutAnEnvNothingIsWritten(): void
    {
        $this->expectException(InstallException::class);
        (new EnvFileUpdater($this->dir))->update(['PS_API_KEY' => 'X'], []);
    }

    public function testAKeyOverriddenElsewhereIsRefusedBecauseTheChangeWouldNotApply(): void
    {
        $this->writeEnv("PS_API_KEY='A'\n");
        file_put_contents($this->dir . '/.env.local', "PS_API_KEY=B\n");

        try {
            (new EnvFileUpdater($this->dir))->update(['PS_API_KEY' => 'X'], []);
            self::fail('A key set in .env.local must not be rewritten in .env.');
        } catch (InstallException $e) {
            self::assertStringContainsString('.env.local', $e->getMessage());
        }
        self::assertSame("PS_API_KEY='A'\n", file_get_contents($this->dir . '/.env'));
        self::assertSame([], glob($this->dir . '/.env.bak-*'));
    }

    public function testARealEnvironmentVariableIsRefused(): void
    {
        $this->writeEnv("PS_API_KEY='A'\n");

        $this->expectException(InstallException::class);
        (new EnvFileUpdater($this->dir))->update(['PS_API_KEY' => 'X'], ['PS_API_KEY' => 'from-server', 'SYMFONY_DOTENV_VARS' => 'APP_ENV']);
    }

    public function testAVariableLoadedFromDotenvIsNotARealOne(): void
    {
        $this->writeEnv("PS_API_KEY='A'\n");

        (new EnvFileUpdater($this->dir))->update(['PS_API_KEY' => 'X'], ['PS_API_KEY' => 'A', 'SYMFONY_DOTENV_VARS' => 'APP_ENV,PS_API_KEY']);

        self::assertSame('X', (new Dotenv())->parse((string) file_get_contents($this->dir . '/.env'))['PS_API_KEY']);
    }

    public function testAControlCharacterInAValueIsRefusedBeforeWriting(): void
    {
        $this->writeEnv("PS_API_KEY='A'\n");

        try {
            (new EnvFileUpdater($this->dir))->update(['PS_API_KEY' => "X\nAPP_ENV=dev"], []);
            self::fail('A line break must be refused.');
        } catch (\InvalidArgumentException) {
        }
        self::assertSame("PS_API_KEY='A'\n", file_get_contents($this->dir . '/.env'));
    }
}
