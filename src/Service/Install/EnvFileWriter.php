<?php

declare(strict_types=1);

namespace VenPosTPV\Service\Install;

/**
 * Renders a .env file that Symfony Dotenv reads back byte for byte.
 *
 * Every value is single-quoted, so Dotenv never expands "$VAR" or runs
 * "$(command)". A single quote inside a value is emitted as a double-quoted
 * "'" segment, which Dotenv concatenates with the neighbouring segments.
 */
final class EnvFileWriter
{
    /**
     * @param array<string, string> $values
     */
    public function render(array $values): string
    {
        $lines = ['# Generated by the VenPosTPV installer on ' . gmdate('Y-m-d H:i:s') . ' UTC.'];
        foreach ($values as $name => $value) {
            if (!preg_match('/^[A-Z][A-Z0-9_]*$/', $name)) {
                throw new \InvalidArgumentException(sprintf('Invalid variable name "%s".', $name));
            }
            $lines[] = $name . '=' . $this->quote($value);
        }

        return implode("\n", $lines) . "\n";
    }

    public function quote(string $value): string
    {
        if (preg_match('/[\x00-\x1F\x7F]/', $value)) {
            throw new \InvalidArgumentException('Values cannot contain line breaks or control characters.');
        }

        return "'" . str_replace("'", "'\"'\"'", $value) . "'";
    }
}
